import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {join} from 'node:path';
const root='app/src/main/assets';
const data=JSON.parse(readFileSync(join(root,'female-pelvis-mri-data.json'),'utf8'));
const labels=JSON.parse(readFileSync(join(root,'female-pelvis-mri-labels.json'),'utf8'));
const series=data.series;const frames=series.flatMap(x=>x.frames);
assert.equal(series.length,5);
assert.deepEqual(series.map(x=>x.frames.length),[24,24,22,22,24]);
assert.ok(series.every(x=>x.group==='multiplanar' && x.module==='pelvis'));
assert.equal(frames.length,116);
assert.equal(Object.keys(labels.slices).length,70);
assert.equal(labels.filters.pelvis.length,11);
assert.equal(Object.values(labels.slices).reduce((n,x)=>n+x.points.length,0),2737);
assert.equal(Object.values(labels.slices).reduce((n,x)=>n+x.masks.length,0),51);
assert.ok(frames.every(x=>x.annotation in labels.slices && existsSync(join(root,x.src))));
assert.ok(Object.values(labels.slices).every(x=>x.masks.every(m=>existsSync(join(root,m.src)))));
const html=readFileSync(join(root,'female-pelvis-mri.html'),'utf8');
assert.match(html,/data-module="female-pelvis-mri"/);
assert.match(html,/src="source-mri-viewer.js"/);
assert.match(readFileSync(join(root,'regions.js'),'utf8'),/female-pelvis-mri\.html/);
console.log('Female pelvis 1.30-style source viewer + labels: VERIFIED');
