"""Derive UI metadata from Gradle. --check never changes files."""
from pathlib import Path
import re,sys,json
root=Path(__file__).resolve().parents[1]
s=(root/'app/build.gradle').read_text();version=re.search(r"versionName '([^']+)'",s).group(1);code=int(re.search(r'versionCode (\d+)',s).group(1))
expected='// Generated by tools/release_metadata.py from app/build.gradle.\nexport const APP_VERSION='+json.dumps(version)+';\nexport const APP_CODE='+str(code)+';\n'
p=root/'app/src/main/assets/app-version-data.js'
if '--version' in sys.argv:print(version)
elif '--code' in sys.argv:print(code)
elif '--check' in sys.argv:
 assert p.read_text()==expected,'UI / Gradle version mismatch: run tools/release_metadata.py'
 print('PASS release metadata:',version,code)
else:p.write_text(expected)
