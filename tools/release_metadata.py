"""One Gradle version for the current runtime, release descriptor and UI."""
from pathlib import Path
import argparse, json, re
ROOT=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');p.add_argument('--version',action='store_true');p.add_argument('--code',action='store_true');p.add_argument('--root',type=Path,default=ROOT/'build/runtime-assets');args=p.parse_args()
s=(ROOT/'app/build.gradle').read_text();version=re.search(r"versionName '([^']+)'",s).group(1);code=int(re.search(r'versionCode (\d+)',s).group(1))
config=json.loads((ROOT/'release-inputs/current.json').read_text())
if (version,code)!=(config['version'],config['versionCode']):raise ValueError('Gradle/current descriptor mismatch')
expected='// Generated by tools/release_metadata.py from app/build.gradle.\nexport const APP_VERSION='+json.dumps(version)+';\nexport const APP_CODE='+str(code)+';\n'
target=args.root/'app-version-data.js'
if args.version:print(version)
elif args.code:print(code)
elif args.check:
 if target.read_text()!=expected:raise ValueError('UI/Gradle version mismatch; prepare current runtime')
 print('PASS release metadata:',version,code)
else:
 target.parent.mkdir(parents=True,exist_ok=True);target.write_text(expected)
